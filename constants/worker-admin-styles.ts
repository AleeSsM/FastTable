export function estadoMesaStyle(estado: 'libre' | 'ocupada' | 'reservada') {
  switch (estado) {
    case 'libre':
      return {
        bg: AcSurfaces.successBadge,
        color: AcColors.success,
        label: 'Libre',
      };
    case 'ocupada':
      return {
        bg: AcSurfaces.dangerBadge,
        color: AcColors.danger,
        label: 'Ocupada',
      };
    case 'reservada':
      return {
        bg: AcSurfaces.warningBadge,
        color: AcColors.warning,
        label: 'Reservada',
      };
    default:
      return { bg: AcColors.surface, color: AcColors.textMuted, label: estado };
  }
}
